// 小工具
const 表 = rows => 'const 状态们 = [\n' + rows.map(r => '  ' + r + ',').join('\n') + '\n];';
const 换表 = (code, rows) => code.replace(/const 状态们 = \[[\s\S]*?\n\];/, () => 表(rows));
const 行 = (名字, 样子, 什么时候, 做什么) => `{ 名字: "${名字}", 样子: "${样子}", 什么时候: "${什么时候}", 做什么: "${做什么}" }`;
const 现在叫 = g => get(g, '状态表[现在状态] ? 状态表[现在状态].名字 : null');
const 离 = (g, d) => run(g, `比特.x = 怪兽.x - ${d}; 比特.y = 怪兽.y; 目标 = null;`);
function 能跑(code, n) {
  try { const g = loadGame(code); frames(g, n || 600); return g; } catch (e) { console.log('   出错：', e.message); return null; }
}
function 说(prompt, code) {
  const r = P.run(code || start, prompt, 'make');
  console.log(`   【${prompt.split('\n')[0]}${prompt.includes('\n') ? '…' : ''}】→ ${r ? r.reply + (r.code ? '（改了代码）' : '（没改）') : 'null'}`);
  return r;
}

